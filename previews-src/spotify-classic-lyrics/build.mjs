// Builds the browser preview of Spotify lyrics fix (Classic Lyrics) into
// public/previews/spotify-classic-lyrics/. No dependencies: `node build.mjs`.
//
// Output
//   index.html, preview.css, preview.js, icon.png   preview page: backdrop + window frame (shell/)
//   app/index.html      the app's original src/index.html; one change: renderer script tag (below)
//   app/style.css       original src/style.css, verbatim
//   app/renderer.js     original src/renderer.cjs, verbatim (renamed only for a JavaScript MIME type)
//   app/report-schema.mjs  original, verbatim (dynamically imported by reporting/diagnostics)
//   app/mock-bridge.js  generated: simulated Electron runtime that runs the ORIGINAL preload.cjs,
//                       main.cjs, watcher.cjs, appearance.cjs, updates.cjs, diagnostics.cjs and
//                       reporting.cjs unchanged, over simulated storage/platform/electron/node APIs
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ORIGINAL = join(here, "original");
const SIM = join(here, "sim");
const SHELL = join(here, "shell");
const OUT = resolve(here, "..", "..", "public", "previews", "spotify-classic-lyrics");
const pkg = JSON.parse(readFileSync(join(ORIGINAL, "package.json"), "utf8"));
const read = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n");
const sha256 = (text) => createHash("sha256").update(text).digest("hex").slice(0, 16);

function replaceOnce(text, from, to) {
  const count = text.split(from).length - 1;
  if (count !== 1) throw new Error(`expected exactly one ${JSON.stringify(from)}, found ${count}`);
  return text.replace(from, () => to);
}

// --- mock-bridge.js ----------------------------------------------------------------------------
const MODULES = [
  // [module id, source file, kind]
  ["src/main.cjs", "original/src/main.cjs", "original"],
  ["src/preload.cjs", "original/src/preload.cjs", "original"],
  ["src/watcher.cjs", "original/src/watcher.cjs", "original"],
  ["src/appearance.cjs", "original/src/appearance.cjs", "original"],
  ["src/updates.cjs", "original/src/updates.cjs", "original"],
  ["src/diagnostics.cjs", "original/src/diagnostics.cjs", "original"],
  ["src/reporting.cjs", "original/src/reporting.cjs", "original"],
  ["src/storage.cjs", "sim/storage.cjs", "simulated (replaces the LevelDB layer)"],
  ["src/platform.cjs", "sim/platform.cjs", "simulated (replaces file-system/process access)"],
  ["src/reporting-config.json", "sim/reporting-config.json", "simulated (no real endpoint or key)"],
  ["electron", "sim/electron-main.cjs", "simulated"],
  ["electron@renderer", "sim/electron-renderer.cjs", "simulated"],
  ["electron-updater", "sim/electron-updater.cjs", "simulated"],
  ["node:fs/promises", "sim/node-fs-promises.cjs", "simulated"],
  ["node:path", "sim/node-path.cjs", "simulated"],
  ["node:url", "sim/node-url.cjs", "simulated"],
  ["node:os", "sim/node-os.cjs", "simulated"],
  ["node:crypto", "sim/node-crypto.cjs", "simulated"],
  ["sim/computer.cjs", "sim/computer.cjs", "simulation"],
  ["sim/process.cjs", "sim/process.cjs", "simulation"],
  ["sim/events.cjs", "sim/events.cjs", "simulation"],
  ["sim/host.cjs", "sim/host.cjs", "simulation"],
  ["sim/ipc.cjs", "sim/ipc.cjs", "simulation"],
  ["sim/network.cjs", "sim/network.cjs", "simulation"],
];

// The simulated platform.cjs keeps the original locations() function; make sure it still matches.
const fn = (text, name) => text.match(new RegExp(`function ${name}\\([\\s\\S]*?\\n}\\n`))?.[0];
const originalLocations = fn(read(join(ORIGINAL, "src", "platform.cjs")), "locations");
if (!originalLocations || originalLocations !== fn(read(join(SIM, "platform.cjs")), "locations")) {
  throw new Error("sim/platform.cjs locations() no longer matches the original");
}

function moduleSource(id, file, kind) {
  let text = read(join(here, file)).trimEnd();
  if (file.endsWith(".json")) return `${JSON.stringify(id)}: function (module) {\nmodule.exports = ${JSON.stringify(JSON.parse(text))};\n}`;
  text = text.replaceAll("__APP_VERSION__", pkg.version).replaceAll("__PRODUCT_NAME__", pkg.productName);
  const label = kind === "original" ? `ORIGINAL ${file.replace(/^original\//, "")}, verbatim (sha256 ${sha256(read(join(here, file)))})` : `${kind}: previews-src/spotify-classic-lyrics/${file}`;
  return `// ===== ${id} -- ${label} =====\n${JSON.stringify(id)}: function (module, exports, require, process, __dirname, __filename, fetch) {\n${text}\n}`;
}

const bridge = [
  "/* mock-bridge.js -- GENERATED by previews-src/spotify-classic-lyrics/build.mjs; do not edit. See PREVIEW.md.",
  " * Simulated Electron runtime for the browser preview of Spotify lyrics fix (Classic Lyrics).",
  " * It runs the app's ORIGINAL preload.cjs (which defines window.classicLyrics: command + onStatus)",
  " * and ORIGINAL main-process modules unchanged, over in-memory stand-ins for Electron, Node, Spotify's",
  " * settings storage and the operating system. Nothing on the visitor's computer is read or changed,",
  " * and no network request is made. */",
  "(function () {",
  "'use strict';",
  "const definitions = {",
  MODULES.map(([id, file, kind]) => moduleSource(id, file, kind)).join(",\n\n"),
  "};",
  "",
  read(join(SIM, "runtime.js")).trimEnd(),
  "})();",
  "",
].join("\n");

// --- app/index.html ----------------------------------------------------------------------------
let appHtml = read(join(ORIGINAL, "src", "index.html"));
appHtml = replaceOnce(appHtml, '<script src="renderer.cjs"></script>', '<script src="mock-bridge.js"></script><script src="renderer.js"></script>');

// --- write -------------------------------------------------------------------------------------
if (!OUT.endsWith(`${sep}public${sep}previews${sep}spotify-classic-lyrics`)) throw new Error(`refusing to clean ${OUT}`);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, "app"), { recursive: true });
writeFileSync(join(OUT, "app", "index.html"), appHtml);
writeFileSync(join(OUT, "app", "mock-bridge.js"), bridge);
copyFileSync(join(ORIGINAL, "src", "style.css"), join(OUT, "app", "style.css"));
copyFileSync(join(ORIGINAL, "src", "renderer.cjs"), join(OUT, "app", "renderer.js"));
copyFileSync(join(ORIGINAL, "src", "report-schema.mjs"), join(OUT, "app", "report-schema.mjs"));
copyFileSync(join(ORIGINAL, "src", "icon.png"), join(OUT, "icon.png"));
for (const name of ["index.html", "preview.css", "preview.js"]) copyFileSync(join(SHELL, name), join(OUT, name));

const listFiles = (dir) => readdirSync(dir).flatMap((name) => statSync(join(dir, name)).isDirectory() ? listFiles(join(dir, name)) : [join(dir, name)]);
let total = 0;
for (const file of listFiles(OUT)) {
  const size = statSync(file).size; total += size;
  console.log(`  ${relative(OUT, file).padEnd(24)} ${String(size).padStart(7)}`);
}
console.log(`output: ${total} bytes in ${relative(resolve(here, "..", ".."), OUT)} (app version ${pkg.version})`);
