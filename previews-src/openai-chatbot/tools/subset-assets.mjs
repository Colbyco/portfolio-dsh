// [preview] Generates self-hosted, subset font assets for the portfolio preview build.
//
// The 2022 app loaded the *entire* Material Design Icons webfont (@mdi/font 5.9.55,
// ~318 KB woff2 + ~330 KB CSS) to draw 4 icons, and pulled Roboto from Google Fonts at runtime
// via webfontloader. This script keeps the exact same fonts but subsets them, so the preview
// makes zero third-party requests and stays small:
//   * MDI 5.9.55 (from the original @mdi/font dependency)  -> only the glyphs the UI uses
//   * Roboto (from the original roboto-fontface dependency) -> the same weights the original
//     Google Fonts request asked for (100,300,400,500,700,900, normal), Latin subset
//
// Output (committed, so a normal `npm run build` needs no Python):
//   src/portfolio/generated/mdi-subset.css, mdi-subset.woff2
//   src/portfolio/generated/roboto.css, roboto-<weight>.woff2
//
// Requires Python with fontTools + brotli (`python -m fontTools.subset`). Run: npm run assets
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src', 'portfolio', 'generated')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const subset = (input, output, unicodes) =>
  execFileSync('python', [
    '-m', 'fontTools.subset', input,
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    '--layout-features=*',
    '--no-hinting',
    '--desubroutinize',
    `--output-file=${output}`,
  ], { stdio: 'inherit' })

// ---- Material Design Icons: only the icons used by HelloWorld.vue (v-btn icon="mdi-...") ----
const ICONS = ['cog-outline', 'github', 'linkedin', 'email']
const mdiDir = join(root, 'node_modules', '@mdi', 'font')
const mdiCss = readFileSync(join(mdiDir, 'css', 'materialdesignicons.css'), 'utf8')
const base = mdiCss.match(/\.mdi:before,\s*\.mdi-set \{[^}]*\}/)[0]
const rules = ICONS.map((name) => {
  const rule = mdiCss.match(new RegExp(`\\.mdi-${name}::before \\{[^}]*\\}`))
  if (!rule) throw new Error(`icon not found: mdi-${name}`)
  return rule[0]
})
const codepoints = rules.map((r) => 'U+' + r.match(/content: "\\([0-9A-F]+)"/)[1])
subset(join(mdiDir, 'fonts', 'materialdesignicons-webfont.ttf'), join(out, 'mdi-subset.woff2'), codepoints.join(','))
writeFileSync(join(out, 'mdi-subset.css'), `/* Generated by tools/subset-assets.mjs from @mdi/font 5.9.55: only ${ICONS.map((n) => 'mdi-' + n).join(', ')}. */
@font-face {
  font-family: "Material Design Icons";
  src: url("./mdi-subset.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
}

${base}

${rules.join('\n\n')}
`)

// ---- Roboto: same weights as the original Google Fonts request, Latin subset ----
// (unicode-range = Google Fonts' "latin" range)
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
const WEIGHTS = { 100: 'Thin', 300: 'Light', 400: 'Regular', 500: 'Medium', 700: 'Bold', 900: 'Black' }
const robotoDir = join(root, 'node_modules', 'roboto-fontface', 'fonts', 'roboto')
let robotoCss = '/* Generated by tools/subset-assets.mjs from roboto-fontface 0.10.0 (Latin subset). Replaces the runtime Google Fonts request "Roboto:100,300,400,500,700,900&display=swap". */\n'
for (const [weight, name] of Object.entries(WEIGHTS)) {
  subset(join(robotoDir, `Roboto-${name}.woff2`), join(out, `roboto-${weight}.woff2`), LATIN)
  robotoCss += `@font-face {
  font-family: "Roboto";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("./roboto-${weight}.woff2") format("woff2");
  unicode-range: ${LATIN.replaceAll(',', ', ')};
}
`
}
writeFileSync(join(out, 'roboto.css'), robotoCss)
console.log('generated', out)
